/**
 * Общие поля каждой записи. Они нужны, чтобы позже добавить синхронизацию между устройствами,
 * не переделывая хранилище: по ним видно, что и когда менялось, а удалённое не исчезает бесследно.
 */
export interface SyncFields {
  /** Уникальный номер записи (UUID), одинаковый на всех устройствах. */
  id: string;
  /** Когда создана, миллисекунды с 1970 года. */
  createdAt: number;
  /** Когда изменена в последний раз. */
  updatedAt: number;
  /** Когда удалена. Удалённая запись остаётся в базе с этой отметкой («надгробие»). */
  deletedAt?: number;
  /** Номер версии записи: растёт с каждым изменением. */
  rev: number;
}

/** Важность: 0 — без отметки, 1 — срочно, 2 — важно, 3 — можно позже. */
export type Priority = 0 | 1 | 2 | 3;

export interface Task extends SyncFields {
  title: string;
  notes?: string;
  priority: Priority;
  /** День, на который запланировано дело, по местному времени: «2026-10-09». Без даты — дело во «Входящих». */
  dueDate?: string;
  /** Время «18:00», если указано. */
  dueTime?: string;
  /** Крайний срок «2026-10-15» (шаг 13). */
  deadline?: string;
  projectId?: string;
  /** Родительское дело — для подзадач (шаг 12). */
  parentId?: string;
  /** Когда дело отмечено выполненным. Нет значения — дело открыто. */
  completedAt?: number;
  /** Порядок в списке: меньше — выше. */
  order: number;
  /** Правило повторения (шаг 15). */
  repeat?: string;
}

/** Таблицы, изменения в которых попадают в очередь синхронизации. */
export type SyncedTable = 'tasks';

/** Запись очереди изменений (outbox): что и когда поменялось на этом устройстве. */
export interface Change {
  seq?: number;
  table: SyncedTable;
  id: string;
  op: 'put' | 'delete';
  at: number;
}

/** Служебные значения этого устройства. Не синхронизируются. */
export interface Meta {
  key: string;
  value: unknown;
}
